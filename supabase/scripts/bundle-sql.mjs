// Concatenates all migrations into ONE file you can paste into the Supabase SQL editor.
//   node supabase/scripts/bundle-sql.mjs   ->   supabase/khatafy_all_in_one.sql
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const parts = [`-- Khatafy: complete database setup (${files.length} migrations). Safe to run once on a NEW Supabase project.\n-- Generated by supabase/scripts/bundle-sql.mjs - do not edit; edit the files in supabase/migrations instead.\n`];
for (const f of files) parts.push(`\n-- ============================================================\n-- ${f}\n-- ============================================================\n${readFileSync(join(dir, f), 'utf8')}`);
const out = join(root, 'khatafy_all_in_one.sql');
writeFileSync(out, parts.join('\n'));
console.log(`Wrote ${out} (${files.length} migrations)`);
